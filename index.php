    <script>$(document).ready(function () {

    $(".jewellery-testimonial-section").each(function () {

        var section = $(this);

        var testimonial = section.find(
            ".jewellery-testimonial-slider"
        );

        var progress = section.find(
            ".testimonial-progress button"
        );

        var total = testimonial.children(".item").length;

        var reduceMotion = window.matchMedia(
            "(prefers-reduced-motion: reduce)"
        ).matches;


        function formatNumber(number) {

            return number < 10 ? "0" + number : number;

        }


        /* Update Slide Number */

        function updatePagination(event) {

            if (!event.relatedTarget || !event.item) {
                return;
            }

            var current = event.relatedTarget.relative(
                event.item.index
            );

            section.find(".testimonial-current")
                .text(formatNumber(current + 1));

            section.find(".testimonial-total")
                .text(formatNumber(total));

            progress.removeClass("active")
                .removeAttr("aria-current");

            progress.eq(current)
                .addClass("active")
                .attr("aria-current", "true");

        }


        /* Initialize Slider */

        testimonial.owlCarousel({

            items: 1,

            loop: true,

            margin: 30,

            nav: false,

            dots: false,

            autoplay: !reduceMotion,

            autoplayTimeout: 5500,

            autoplayHoverPause: true,

            smartSpeed: reduceMotion ? 0 : 800,

            mouseDrag: true,

            touchDrag: true,

            autoHeight: true,

            onInitialized: updatePagination,

            onChanged: updatePagination

        });


        /* Custom Pagination Click */

        progress.on("click", function () {

            var slide = Number($(this).attr("data-slide"));

            testimonial.trigger("to.owl.carousel", [
                slide,
                reduceMotion ? 0 : 800,
                true
            ]);

        });

    });

});</script>
