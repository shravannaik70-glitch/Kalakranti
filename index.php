    <script>
    // Avoid an error on pages without the counter section.
    var counted = 0;
    $(window).on('scroll', function() {
        var $counter = $('#counter');
        if (!$counter.length || counted) return;
        var oTop = $counter.offset().top - window.innerHeight;
        if ($(window).scrollTop() > oTop) {
            $('.count').each(function() {
                var $this = $(this),
                    countTo = $this.attr('data-count');
                $({
                    countNum: Number($this.text()) || 0
                }).animate({
                    countNum: Number(countTo) || 0
                }, {
                    duration: 2000,
                    easing: 'swing',
                    step: function() {
                        $this.text(Math.floor(this.countNum));
                    },
                    complete: function() {
                        $this.text(Math.floor(this.countNum));
                    }
                });
            });
            counted = 1;
        }
    });
    </script>
    <script>
    // Prevent ScrollTrigger errors if libraries or target sections aren't present.
    if (window.gsap && window.ScrollTrigger) {
        gsap.registerPlugin(ScrollTrigger);
        var intro = document.querySelector('.sticky-intro');
        var services = document.querySelector('.services-column');
        if (intro && services) {
            ScrollTrigger.matchMedia({
                '(min-width: 992px)': function() {
                    ScrollTrigger.create({
                        trigger: intro,
                        start: 'top 90px',
                        endTrigger: services,
                        end: function() {
                            return 'bottom ' + (intro.offsetHeight + 30) + 'px';
                        },
                        pin: intro,
                        pinSpacing: false,
                        invalidateOnRefresh: true
                    });
                }
            });
        }
        window.addEventListener('load', function() {
            ScrollTrigger.refresh();
        });
    }
    </script>
